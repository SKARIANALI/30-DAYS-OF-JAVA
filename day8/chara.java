 class chara {
    public static void main(String[] args) {
        int i, j;
        char ch = 'A';
        for (i = 1; i <= 5; i++) // for rows
        {
            for (j = 1; j <= i; j++) { // for coloumn
                System.out.print(ch + " ");
                ch++;
            }
            System.out.println(); // for next line

        }
    }

    
}



